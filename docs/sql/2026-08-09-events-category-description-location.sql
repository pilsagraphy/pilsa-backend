-- ============================================================
--  일정(events) 테이블 - 캘린더 디자인 반영
--  대상 DB : qa_pilsa (MySQL 8, InnoDB, utf8mb4_0900_ai_ci)
--  작성일  : 2026-08-09
--
--  1) 일정 구분(category) 컬럼 추가
--     - 관리자 화면에서 자유 입력하는 텍스트 (고정 목록 아님, 예: "정기모임")
--  2) location 컬럼 제거
--     - 캘린더 디자인 시안엔 별도 "장소" 입력칸이 없고, 세부사항(description)
--       텍스트 안에 장소 정보가 자유 서술형으로 포함됨. 코드(EventMapper.xml,
--       EventRequest/EventDataResponse) 어디서도 참조하지 않아 제거 대상.
--       실제 DB에 이미 있을 수도, 없을 수도 있어 IF EXISTS로 안전하게 처리.
--
--  ※ 이 프로젝트에는 Flyway/Liquibase 가 없어 수동 적용한다.
-- ============================================================


-- ------------------------------------------------------------
-- [사전 확인] 적용 전 현재 상태
-- ------------------------------------------------------------
SELECT event_id, title, description, start_at, end_at, location, user_id
FROM events
ORDER BY event_id;


-- ------------------------------------------------------------
-- 1) category 컬럼 추가 (nullable - 기존 row 백필 없이 안전하게 추가,
--    필수 입력 여부는 애플리케이션 레벨에서 검증)
-- ------------------------------------------------------------
ALTER TABLE `events`
  ADD COLUMN `category` varchar(50) NULL COMMENT '일정 구분 (관리자 자유 입력, 예: 정기모임)' AFTER `title`;


-- ------------------------------------------------------------
-- 2) location 컬럼 제거 (있으면 제거, 없으면 통과)
-- ------------------------------------------------------------
ALTER TABLE `events`
  DROP COLUMN IF EXISTS `location`;


-- ------------------------------------------------------------
-- [사후 확인] 적용 결과
-- ------------------------------------------------------------
SELECT *
FROM events
ORDER BY event_id;


